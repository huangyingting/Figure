export const locales = ["en", "zh-CN"] as const;

export type Locale = (typeof locales)[number];

export const DEFAULT_LOCALE: Locale = "en";
export const LOCALE_COOKIE = "figure_locale";

export function normalizeLocale(value: string | null | undefined): Locale {
  if (!value) return DEFAULT_LOCALE;
  const normalized = value.toLowerCase();
  return normalized === "zh" || normalized.startsWith("zh-") ? "zh-CN" : "en";
}

export function requestLocale(request: Request): Locale {
  const cookie = request.headers.get("cookie")
    ?.split(";")
    .map((item) => item.trim())
    .find((item) => item.startsWith(`${LOCALE_COOKIE}=`))
    ?.slice(LOCALE_COOKIE.length + 1);
  return normalizeLocale(cookie ?? request.headers.get("accept-language"));
}

export function requestTranslator(request: Request) {
  return createTranslator(requestLocale(request));
}

